export function useTranslation() {
  const { preferences } = usePreferences();
  const lang = preferences.language || 'en';
  
  const t = (key: string): string => {
    return dictionaries[lang]?.[key] || dictionaries['en'][key] || key;
  };

  return { t, lang };
}
